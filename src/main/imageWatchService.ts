import path from 'path';

export interface ImageDirectoryWatcher {
  on(
    event: string,
    listener: (changedPath: string) => void,
  ): ImageDirectoryWatcher;
  close(): Promise<void> | void;
}

export interface ImageWatchDependencies<Tags> {
  root: () => string;
  watchDirectory: (directory: string) => ImageDirectoryWatcher;
  readTags: (file: string) => Promise<Tags>;
  writeTags: (file: string, tags: Tags) => Promise<unknown>;
  fingerprint: (file: string) => Promise<string>;
  changed: (relativePath: string) => void;
  report: (error: unknown) => void;
}

interface WatchedImage<Tags> {
  path: string;
  directory: string;
  relativePath: string;
  owners: Map<number, number>;
  tags: Tags | null;
  initialized: Promise<void>;
  dirty: boolean;
  running?: Promise<void>;
  lastHandledVersion?: string;
}

async function settleOwnedTasks(
  tasks: readonly (Promise<unknown> | undefined)[],
): Promise<void> {
  const results = await Promise.allSettled(tasks);
  const failed = results.find((result) => result.status === 'rejected');
  if (failed?.status === 'rejected') throw failed.reason;
}

/** Owns native watchers and serializes metadata writes for each image, without timers. */
export class ImageWatchService<Tags = unknown> {
  readonly directories = new Map<string, ImageDirectoryWatcher>();

  readonly files = new Map<string, WatchedImage<Tags>>();

  private readonly directoryFiles = new Map<string, Set<string>>();

  constructor(private readonly deps: ImageWatchDependencies<Tags>) {}

  private normalize(inputPath: string): string {
    return path.resolve(this.deps.root(), inputPath);
  }

  private isLive(entry: WatchedImage<Tags>): boolean {
    return this.files.get(entry.path) === entry;
  }

  async watch(owner: number, inputPath: string): Promise<void> {
    const absolute = this.normalize(inputPath);
    let entry = this.files.get(absolute);
    if (!entry) {
      entry = {
        path: absolute,
        directory: path.dirname(absolute),
        relativePath: path
          .relative(this.deps.root(), absolute)
          .split(path.sep)
          .join('/'),
        owners: new Map(),
        tags: null,
        initialized: Promise.resolve(),
        dirty: false,
      };
      this.files.set(absolute, entry);
      const captured = entry;
      // Publish ownership before async work: unwatch/window close can release
      // an entry even while ExifTool is still reading its original metadata.
      entry.initialized = Promise.resolve()
        .then(() => this.deps.readTags(absolute))
        .then((tags) => {
          if (this.isLive(captured)) captured.tags = tags;
          return undefined;
        })
        .catch((error) => this.deps.report(error));
      try {
        this.addDirectory(entry);
      } catch (error) {
        this.files.delete(absolute);
        throw error;
      }
    }
    entry.owners.set(owner, (entry.owners.get(owner) ?? 0) + 1);
    await entry.initialized;
  }

  private addDirectory(entry: WatchedImage<Tags>): void {
    let members = this.directoryFiles.get(entry.directory);
    if (!members) {
      members = new Set();
      const watcher = this.deps.watchDirectory(entry.directory);
      const changed = (changedPath: string) => {
        const candidate = path.resolve(entry.directory, changedPath);
        const current = this.files.get(candidate);
        if (current) this.schedule(current);
      };
      watcher.on('change', changed);
      // Editors that save by replacing a file can surface an add event.
      watcher.on('add', changed);
      this.directories.set(entry.directory, watcher);
      this.directoryFiles.set(entry.directory, members);
    }
    members.add(entry.path);
  }

  private schedule(entry: WatchedImage<Tags>): void {
    entry.dirty = true;
    if (entry.running) return;
    entry.running = this.processChanges(entry)
      .catch((error) => this.deps.report(error))
      .finally(() => {
        entry.running = undefined;
        if (entry.dirty && this.isLive(entry)) this.schedule(entry);
      });
  }

  private async processChanges(entry: WatchedImage<Tags>): Promise<void> {
    await entry.initialized;
    while (entry.dirty && this.isLive(entry)) {
      entry.dirty = false;
      const before = await this.deps.fingerprint(entry.path);
      if (!this.isLive(entry)) return;
      // The native event generated by our own completed metadata write is not
      // another editor save. Matching the file version avoids a write loop.
      if (before === entry.lastHandledVersion) continue;
      try {
        if (entry.tags !== null)
          await this.deps.writeTags(entry.path, entry.tags);
      } catch (error) {
        this.deps.report(error);
      }
      // Record actual completion; a later native event with a new version is
      // processed. No delayed second write and no process-wide exclusion flag.
      try {
        entry.lastHandledVersion = await this.deps.fingerprint(entry.path);
      } catch (error) {
        this.deps.report(error);
      }
      if (this.isLive(entry)) this.deps.changed(entry.relativePath);
    }
  }

  async unwatch(owner: number, inputPath: string): Promise<void> {
    const entry = this.files.get(this.normalize(inputPath));
    if (!entry) return;
    const refs = entry.owners.get(owner) ?? 0;
    if (refs > 1) entry.owners.set(owner, refs - 1);
    else entry.owners.delete(owner);
    if (entry.owners.size === 0) await this.remove(entry);
  }

  private async remove(entry: WatchedImage<Tags>): Promise<void> {
    if (!this.isLive(entry)) return;
    this.files.delete(entry.path);
    entry.dirty = false;
    const members = this.directoryFiles.get(entry.directory);
    members?.delete(entry.path);
    const pending = [entry.initialized, entry.running];
    if (members?.size === 0) {
      this.directoryFiles.delete(entry.directory);
      const watcher = this.directories.get(entry.directory);
      this.directories.delete(entry.directory);
      try {
        pending.push(Promise.resolve(watcher?.close()));
      } catch (error) {
        pending.push(Promise.reject(error));
      }
    }
    await settleOwnedTasks(pending);
  }

  async releaseOwner(owner: number): Promise<void> {
    const released: Promise<void>[] = [];
    for (const entry of this.files.values()) {
      entry.owners.delete(owner);
      if (entry.owners.size === 0) released.push(this.remove(entry));
    }
    await settleOwnedTasks(released);
  }

  async forgetPath(inputPath: string): Promise<void> {
    const entry = this.files.get(this.normalize(inputPath));
    if (entry) await this.remove(entry);
  }

  async forgetDirectory(inputPath: string): Promise<void> {
    const directory = this.normalize(inputPath);
    const released: Promise<void>[] = [];
    for (const entry of this.files.values()) {
      if (entry.path.startsWith(directory + path.sep))
        released.push(this.remove(entry));
    }
    await settleOwnedTasks(released);
  }

  async dispose(): Promise<void> {
    await settleOwnedTasks(
      Array.from(this.files.values(), (entry) => this.remove(entry)),
    );
  }

  /** Completion barrier for teardown and deterministic lifecycle verification. */
  async idle(): Promise<void> {
    const activeWrites = () =>
      Array.from(this.files.values()).flatMap((entry) =>
        entry.running ? [entry.running] : [],
      );
    for (
      let pending = activeWrites();
      pending.length > 0;
      pending = activeWrites()
    ) {
      await settleOwnedTasks(pending);
    }
  }
}
